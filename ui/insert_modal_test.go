func TestTableColumnMeta_Helpers(t *testing.T) {
	autoCol := TableColumnMeta{Name: "id", DataType: "int", ColumnType: "int(11)", Extra: "auto_increment", Key: "PRI"}
	if !autoCol.IsAutoGenerated() {
		t.Errorf("expected id column to be auto-generated")
	}
	if autoCol.IsRequiredOnInsert() {
		t.Errorf("expected auto_increment column not to be required on insert")
	}

	nullableCol := TableColumnMeta{Name: "bio", DataType: "text", ColumnType: "text", IsNullable: true}
	if nullableCol.IsAutoGenerated() || nullableCol.IsRequiredOnInsert() {
		t.Errorf("expected nullable column not to be auto-generated or required")
	}

	defaultCol := TableColumnMeta{Name: "created_at", DataType: "timestamp", ColumnType: "timestamp", HasDefault: true, DefaultValue: "CURRENT_TIMESTAMP"}
	if defaultCol.IsRequiredOnInsert() {
		t.Errorf("expected column with DEFAULT not to be required on insert")
	}

	reqCol := TableColumnMeta{Name: "email", DataType: "varchar", ColumnType: "varchar(255)", IsNullable: false, HasDefault: false}
	if !reqCol.IsRequiredOnInsert() {
		t.Errorf("expected NOT NULL column without default to be required on insert")
	}
}

func TestValidateInsertValue(t *testing.T) {
	intCol := TableColumnMeta{Name: "age", DataType: "int", ColumnType: "int", IsNullable: false}
	decCol := TableColumnMeta{Name: "price", DataType: "decimal", ColumnType: "decimal(10,2)", IsNullable: true}
	strCol := TableColumnMeta{Name: "notes", DataType: "varchar", ColumnType: "varchar(100)", IsNullable: true}

	if err := ValidateInsertValue(intCol, InsertFieldValue{Text: ""}); err == nil {
		t.Errorf("expected error for missing required int column")
	}
	if err := ValidateInsertValue(intCol, InsertFieldValue{Text: "not_a_num"}); err == nil {
		t.Errorf("expected error for non-integer input in int column")
	}
	if err := ValidateInsertValue(intCol, InsertFieldValue{IsNull: true}); err == nil {
		t.Errorf("expected error setting NULL on NOT NULL column")
	}
	if err := ValidateInsertValue(intCol, InsertFieldValue{Text: "42"}); err != nil {
		t.Errorf("unexpected error for valid int: %v", err)
	}

	if err := ValidateInsertValue(decCol, InsertFieldValue{Text: "19.99"}); err != nil {
		t.Errorf("unexpected error for valid decimal: %v", err)
	}
	if err := ValidateInsertValue(decCol, InsertFieldValue{ExplicitEmpty: true}); err == nil {
		t.Errorf("expected error setting explicit empty string on decimal column")
	}
	if err := ValidateInsertValue(decCol, InsertFieldValue{IsNull: true}); err != nil {
		t.Errorf("unexpected error setting NULL on nullable decimal column: %v", err)
	}

	if err := ValidateInsertValue(strCol, InsertFieldValue{ExplicitEmpty: true}); err != nil {
		t.Errorf("expected explicit empty string to be valid for varchar column: %v", err)
	}
}

func TestBuildParameterizedInsertQuery(t *testing.T) {
	cols := []TableColumnMeta{
		{Name: "id", DataType: "int", ColumnType: "int", Extra: "auto_increment", Key: "PRI"},
		{Name: "username", DataType: "varchar", ColumnType: "varchar(50)", IsNullable: false},
		{Name: "bio", DataType: "text", ColumnType: "text", IsNullable: true},
		{Name: "nickname", DataType: "varchar", ColumnType: "varchar(50)", IsNullable: true},
		{Name: "status", DataType: "varchar", ColumnType: "varchar(20)", IsNullable: false, HasDefault: true, DefaultValue: "active"},
	}

	values := map[string]InsertFieldValue{
		"id":       {Text: ""},                  // omitted -> auto_increment
		"username": {Text: "alice"},             // provided literal
		"bio":      {IsNull: true},              // explicit SQL NULL
		"nickname": {ExplicitEmpty: true},       // explicit empty string ""
		"status":   {Text: ""},                  // omitted -> DEFAULT 'active'
	}

	query, args, preview, err := BuildParameterizedInsertQuery("appdb", "users", cols, values)
	if err != nil {
		t.Fatalf("unexpected error building insert query: %v", err)
	}

	wantQuery := "INSERT INTO `appdb`.`users` (`username`, `bio`, `nickname`) VALUES (?, ?, ?)"
	if query != wantQuery {
		t.Errorf("got query %q, want %q", query, wantQuery)
	}
	if len(args) != 3 {
		t.Fatalf("expected 3 args, got %d", len(args))
	}
	if args[0] != "alice" || args[1] != nil || args[2] != "" {
		t.Errorf("unexpected args: %#v", args)
	}
	if !strings.Contains(preview, "INSERT INTO `appdb`.`users`") || !strings.Contains(preview, "'alice'") {
		t.Errorf("unexpected preview SQL: %q", preview)
	}

	// Empty columns omitted (all auto/default) -> INSERT INTO ... () VALUES ()
	autoOnly := []TableColumnMeta{
		{Name: "id", DataType: "int", ColumnType: "int", Extra: "auto_increment"},
	}
	qEmpty, argsEmpty, _, errEmpty := BuildParameterizedInsertQuery("appdb", "ticks", autoOnly, map[string]InsertFieldValue{})
	if errEmpty != nil {
		t.Fatalf("unexpected error on empty values insert: %v", errEmpty)
	}
	if qEmpty != "INSERT INTO `appdb`.`ticks` () VALUES ()" || len(argsEmpty) != 0 {
		t.Errorf("got (%q, %v), want empty VALUES ()", qEmpty, argsEmpty)
	}
}

func TestBuildInsertFormUI_HotkeysAndGuards(t *testing.T) {
	origRO := ActiveReadOnly
	origObj := activeGridObject
	origType := activeGridObjectType
	defer func() {
		ActiveReadOnly = origRO
		activeGridObject = origObj
		activeGridObjectType = origType
	}()

	app := tview.NewApplication()
	mainFlex = tview.NewFlex()
	CreateLayoutWithFooter(app, mainFlex)
	tbl := tview.NewTable()

	cols := []TableColumnMeta{
		{Name: "id", DataType: "int", ColumnType: "int", Extra: "auto_increment", Key: "PRI"},
		{Name: "name", DataType: "varchar", ColumnType: "varchar(50)", IsNullable: false},
		{Name: "notes", DataType: "text", ColumnType: "text", IsNullable: true},
	}

	modal := buildInsertRowModalUI(app, nil, "testdb", "items", cols, tbl)
	if modal == nil {
		t.Fatalf("expected non-nil insert modal")
	}

	// Read-Only guard via table '+' shortcut must not panic and should present error modal
	ActiveReadOnly = true
	activeGridObject = "items"
	activeGridObjectType = "TABLE"
	setupTableInputCapture(app, tbl)
	handler := tbl.GetInputCapture()
	if handler == nil {
		t.Fatalf("expected table input capture to be configured")
	}
	ret := handler(tcell.NewEventKey(tcell.KeyRune, '+', 0))
	if ret != nil {
		t.Errorf("expected '+' key to be consumed in Read-Only mode")
	}

	// Non-TABLE guard via 'a' shortcut
	ActiveReadOnly = false
	activeGridObjectType = "VIEW"
	retView := handler(tcell.NewEventKey(tcell.KeyRune, 'a', 0))
	if retView != nil {
		t.Errorf("expected 'a' key to be consumed cleanly with footer hint on non-TABLE view")
	}
}
